class AdvisorFormatterNode:
    """Generate the advisor response via a single constrained LLM call.

    The LLM receives only validated data blocks and a planner-generated intent
    summary — never the raw user message or any tool names.
    """

    def __init__(self, model: BaseChatModel) -> None:
        self.model = model
        self._city_extractor    = silent(model.with_structured_output(_CityExtraction))
        self._concert_extractor = silent(
            model.with_structured_output(_ConcertResults, method="function_calling")
        )
        self._events_extractor = silent(
            model.with_structured_output(_SpecialEventsResults, method="function_calling")
        )

    def __call__(self, state: AgentState) -> dict:
        # Clean up any orphaned tool-call message left in history
        messages   = list(state.get("messages", []))
        remove_ops: list[RemoveMessage] = []
        if messages and getattr(messages[-1], "tool_calls", None):
            orphan = messages[-1]
            messages = messages[:-1]
            if orphan.id is not None:
                remove_ops.append(RemoveMessage(id=orphan.id))

        tool_results     = list(state.get("advisor_last_tool_results") or [])
        response_mode    = state.get("advisor_response_mode") or "tool_call"
        extracted_events = None  # set by special-events path; written to state if non-empty

        # --- Routing ---
        if response_mode == "greeting" or (not tool_results and response_mode != "conversational"):
            full_response = _GREETING_RESPONSE

        elif response_mode == "conversational":
            full_response = self._render_conversational(state, messages)

        else:
            tool_names = {tr["tool_name"] for tr in tool_results}
            intent     = state.get("advisor_intent_summary", "")

            if "search_concerts" in tool_names:
                data_block   = self._extract_concert_data(tool_results)
                concert_tr   = next(tr for tr in tool_results if tr["tool_name"] == "search_concerts")
                concert_args = concert_tr.get("args", {})
                # _browse_url is injected by _tavily_extract_metro into the first snippet
                snippets     = concert_tr.get("result") or []
                browse_url   = next(
                    (s["_browse_url"] for s in snippets if isinstance(s, dict) and "_browse_url" in s),
                    None,
                )
                extracted_events = None

            elif "search_special_events" in tool_names:
                extracted_events, data_block = self._extract_special_events_data(tool_results, state)
                events_tr    = next(tr for tr in tool_results if tr["tool_name"] == "search_special_events")
                events_args  = events_tr.get("args", {})
                concert_args = {}
                browse_url   = None

            else:
                data_block       = format_results_for_llm(tool_results)
                concert_args     = {}
                browse_url       = None
                extracted_events = None

            full_response = self._call_formatter_llm(
                intent, data_block, tool_names, state, concert_args, browse_url
            )

            if "search_special_events" in tool_names:
                events_closer = _build_events_closer(
                    events_args.get("city"), events_args.get("month"),
                    has_events=bool(extracted_events),
                )
                if events_closer:
                    full_response = full_response.rstrip() + "\n\n" + events_closer

        response     = AIMessage(content=full_response)
        shown_cities = self._extract_cities(full_response, state)

        result: dict = {
            "messages": remove_ops + [response],
            "advisor_shown_cities": shown_cities,
        }
        if extracted_events:
            result["special_events_data"] = extracted_events
        return result

    # ------------------------------------------------------------------
    # Main LLM formatter call
    # ------------------------------------------------------------------

    def _call_formatter_llm(
        self,
        intent: str,
        data_block: str,
        tool_names: set[str],
        state: AgentState,
        concert_args: dict | None = None,
        browse_url: str | None = None,
    ) -> str:
        has_origin = bool(state.get("current_city"))
        closer     = closer_guidance_for(tool_names, has_origin)

        # For concert and special-events searches the closer is built deterministically
        # so suggestions are always precise. Tell the LLM to omit it — we append ourselves.
        if concert_args:
            concert_closer = _build_concert_closer(concert_args, browse_url)
            closer = "Do NOT add a closing sentence — one will be appended automatically."
        elif "search_special_events" in tool_names:
            concert_closer = None
            closer = "Do NOT add a closing sentence — one will be appended automatically."
        else:
            concert_closer = None

        system = _FORMATTER_SYSTEM.format(
            security_rules=SECURITY_RULES,
            closer_guidance=closer,
        )

        user_content = (
            f"INTENT:\n{intent}\n\nDATA:\n{data_block}"
            if intent else
            f"DATA:\n{data_block}"
        )

        response = self.model.invoke([
            {"role": "system", "content": system},
            {"role": "user",   "content": user_content},
        ])

        text = response.content.rstrip()
        if concert_closer:
            text = text + "\n\n" + concert_closer
        return text

    # ------------------------------------------------------------------
    # Concert path: Pydantic extraction → clean data block → LLM formatter
    # ------------------------------------------------------------------

    def _extract_concert_data(self, tool_results: list[dict]) -> str:
        """Extract structured concert events from raw web snippets, return as a clean data block."""
        concert_tr = next(tr for tr in tool_results if tr["tool_name"] == "search_concerts")
        snippets   = concert_tr.get("result") or []
        args       = concert_tr.get("args", {})

        today_str        = datetime.date.today().strftime("%B %d, %Y")
        is_artist_search = bool(args.get("artist"))
        requested_month  = args.get("month", "")

        mode_note = (
            f"SPECIFIC ARTIST: Only include events explicitly naming '{args['artist']}' AND a specific date."
            if is_artist_search else
            "CITY/MONTH SEARCH: Include any event with an explicit artist name AND a specific date."
        )
        month_filter = (
            f"\nMONTH FILTER (STRICT): Only include events in {requested_month}. "
            f"Discard any event with a date outside {requested_month}."
            if requested_month else ""
        )

        snippets_text = "\n\n".join(
            f"[Snippet {i+1}]\nTitle: {s.get('title','')}\n"
            f"Content: {s.get('content','')}\nURL: {s.get('url','')}"
            for i, s in enumerate(snippets)
            if isinstance(s, dict) and "content" in s
        )

        artist = args.get("artist", "")
        city   = args.get("city", "")
        month  = args.get("month", "")
        label  = "Concert Events" + (
            " — " + ", ".join(filter(None, [artist, city, month]))
            if any([artist, city, month]) else ""
        )

        if not snippets_text:
            return f"[{label}]\nstatus: No concert data returned for this search."

        try:
            extraction: _ConcertResults = self._concert_extractor.invoke([
                {
                    "role": "system",
                    "content": (
                        f"TODAY'S DATE: {today_str}\n\n"
                        f"Extract confirmed upcoming concerts from these snippets.\n"
                        f"{mode_note}{month_filter}\n"
                        "Discard events before today's date.\n"
                        "Discard genre pages, 'similar artists' roundups, or snippets with no specific date.\n\n"
                        "URL RULES: For the url field, use ONLY individual concert or event page URLs "
                        "(e.g. containing '/concerts/', '/festivals/', '/e/', or a ticket page). "
                        "NEVER use metro-area listing URLs (containing 'metro-areas') — those link "
                        "to a whole month's listings, not a specific show. If no individual URL is "
                        "found in the snippet for an event, leave url as null.\n\n"
                        "DATE RULES (strict):\n"
                        "- If an explicit day is stated in the content → use it (e.g. 'August 22, 2026').\n"
                        "- JSON ISO dates like '2026-08-22' → convert to 'August 22, 2026'.\n"
                        "- If only the month/year is given with NO specific day → use 'August 2026' "
                        "(month + year only, NO day number).\n"
                        "- NEVER invent a day. NEVER default to the 1st or any other day when the "
                        "content does not explicitly state one. This is the most common error — avoid it.\n"
                        "- Year-only dates are not valid — discard those events.\n\n"
                        "FESTIVAL CONSOLIDATION (critical):\n"
                        "When snippets mention multiple artists at the SAME festival on the SAME day:\n"
                        "  → Create exactly ONE _ConcertEvent entry for the festival\n"
                        "  → Set event_name to the festival name (e.g. 'All Points East 2026')\n"
                        "  → Put ALL artists in the artists[] list\n"
                        "  → Set date/venue/city/url from the festival listing\n"
                        "  → Do NOT create one entry per artist\n"
                        "For standalone single-artist concerts, leave event_name and artists empty."
                    ),
                },
                {"role": "user", "content": snippets_text},
            ])
        except Exception:
            extraction = _ConcertResults(events=[], no_results_message=None)

        # Deterministic post-extraction filters (LLM cannot bypass these)
        if extraction.events:
            # 1. Date completeness — drop events without at least a month+year.
            #    Accept both "August 22, 2026" (with day) and "August 2026" (month only).
            #    Reject empty, "TBC", year-only, or digit-free strings.
            _VAGUE_DATES = {"", "tbc", "unknown", "?", "various", "dates tbc"}
            extraction.events = [
                ev for ev in extraction.events
                if ev.date
                and ev.date.strip().lower() not in _VAGUE_DATES
                and any(ch.isdigit() for ch in ev.date)   # must have at least one digit
                and len(ev.date.strip()) > 4              # "2026" alone is not enough
            ]
            # 2. Month filter — discard events with hallucinated dates outside requested month
            if requested_month:
                extraction.events = [
                    ev for ev in extraction.events
                    if _date_matches_month(ev.date, requested_month)
                ]
            # 3. URL filter — strip bare homepage URLs (e.g. www.bandsintown.com with no path)
            for ev in extraction.events:
                if not _is_specific_url(ev.url):
                    ev.url = None

        if extraction.no_results_message and not extraction.events:
            return f"[{label}]\nstatus: {extraction.no_results_message}"

        if not extraction.events:
            return f"[{label}]\nstatus: No confirmed dates found — shows may not be announced yet."

        lines = []
        for ev in extraction.events:
            if ev.event_name and ev.artists:
                # Festival with consolidated performer list
                parts = [
                    f"festival: {ev.event_name}",
                    f"performers: {', '.join(ev.artists)}",
                    f"date: {ev.date}",
                ]
            elif ev.event_name:
                # Festival but only one artist extracted
                parts = [f"festival: {ev.event_name}", f"performer: {ev.artist}", f"date: {ev.date}"]
            else:
                # Standalone concert
                parts = [f"artist: {ev.artist}", f"date: {ev.date}"]
            if ev.venue:  parts.append(f"venue: {ev.venue}")
            if ev.city:   parts.append(f"city: {ev.city}")
            if ev.genre:  parts.append(f"genre: {ev.genre}")
            if ev.url:    parts.append(f"url: {ev.url}")
            lines.append("- " + " | ".join(parts))

        return f"[{label}]\n" + "\n".join(lines)

    # ------------------------------------------------------------------
    # Special Events path: raw snippets → structured extraction → data block
    # ------------------------------------------------------------------

    def _extract_special_events_data(
        self, tool_results: list[dict], state: AgentState
    ) -> tuple[list[dict], str]:
        """Extract structured special events from Tavily snippets.

        Returns (events_for_state, data_block_for_llm).
        - events_for_state: list of SpecialEvent-compatible dicts (written to state["special_events_data"])
        - data_block_for_llm: clean text block WITHOUT price (passed to formatter LLM)
        """
        events_tr = next(tr for tr in tool_results if tr["tool_name"] == "search_special_events")
        snippets  = events_tr.get("result") or []
        args      = events_tr.get("args", {})

        city  = args.get("city", "")
        month = args.get("month", "")

        # Derive travel year from month arg or trip_start state
        year = month.split()[-1] if month and month.split()[-1].isdigit() else ""
        if not year:
            trip_start = state.get("trip_start", "")
            year = trip_start[:4] if trip_start else str(datetime.date.today().year)

        label = "Special Events" + (
            " — " + ", ".join(filter(None, [city, month])) if any([city, month]) else ""
        )

        snippets_text = "\n\n".join(
            f"[Snippet {i+1}]\nTitle: {s.get('title','')}\n"
            f"Content: {s.get('content','')}\nURL: {s.get('url','')}"
            for i, s in enumerate(snippets)
            if isinstance(s, dict) and "content" in s
        )

        if not snippets_text:
            return [], f"[{label}]\nstatus: No event data returned for this search."

        today_str = datetime.date.today().strftime("%B %d, %Y")

        try:
            extraction: _SpecialEventsResults = self._events_extractor.invoke([
                {
                    "role": "system",
                    "content": (
                        f"TODAY'S DATE: {today_str}\n"
                        f"TRAVEL YEAR: {year}\n"
                        f"DESTINATION CITY: {city}\n\n"
                        "GROUNDING (most important rule): Every event you output MUST come from the "
                        "snippets below. NEVER add an event from your own knowledge or memory. If an "
                        "event is not described in the snippets, do NOT include it — even if you are "
                        "certain it really happens in this city. You are an extractor, not a generator. "
                        "When in doubt, leave it out.\n\n"
                        f"MONTH FILTER: Only include events happening in {month}. Discard events from other months.\n\n"
                        "Extract date-specific special events, festivals, and seasonal happenings "
                        "from these travel article snippets.\n\n"
                        "CITY RULE: Include ONLY events physically held IN the destination city itself. "
                        "Discard events in nearby towns, other islands, or regions requiring separate travel.\n\n"
                        "ANNUAL / RECURRING EVENTS:\n"
                        f"If a snippet describes an event from a previous year (e.g., 'Christmas Market 2024') "
                        f"AND the event is clearly annual or seasonal (markets, festivals, national holidays, "
                        f"seasonal celebrations), project it to {year} and include it. "
                        "Examples of annual events: Christmas markets, Oktoberfest, New Year's fireworks, "
                        "carnival, pride events, harvest festivals, national holiday celebrations.\n"
                        f"DISCARD one-time events that ran only in a specific past year and are unlikely to recur.\n\n"
                        "DATES: In applicable_dates, list each date the event runs in YYYY-MM-DD format, "
                        f"projected to {year}. If it runs all month, list every day of the month. "
                        "Only include dates within the travel window (the month from the search).\n\n"
                        "COST: Extract cost_usd (0.0 = free entry). For free events (markets, street "
                        "festivals), estimate a realistic food/browsing spend ($10–$30 typical).\n\n"
                        "LOCATION: Always fill location_hint with the most specific venue or area name "
                        "mentioned in the article (e.g., 'Gendarmenmarkt', 'Old Town Square').\n\n"
                        "Do NOT include permanent tourist attractions or regular museum opening hours — "
                        "only time-limited, seasonal, or date-specific events."
                    ),
                },
                {"role": "user", "content": snippets_text},
            ])
        except Exception:
            extraction = _SpecialEventsResults(events=[], no_results_message=None)

        if extraction.no_results_message and not extraction.events:
            return [], f"[{label}]\nstatus: {extraction.no_results_message}"

        if not extraction.events:
            return [], f"[{label}]\nstatus: No special events found for this search."

        # Fallback: fill empty applicable_dates with every day of the search month so the
        # itinerary pipeline can inject the event even when the LLM omitted specific dates.
        import calendar as _cal  # noqa: PLC0415
        month_dates: list[str] = []
        month_name_str = month.split()[0] if month else ""
        try:
            month_num   = list(_cal.month_name).index(month_name_str)  # 1–12
            year_int    = int(year)
            _, last_day = _cal.monthrange(year_int, month_num)
            month_dates = [
                f"{year_int}-{month_num:02d}-{d:02d}"
                for d in range(1, last_day + 1)
            ]
        except (ValueError, IndexError):
            pass
        for ev in extraction.events:
            if not ev.applicable_dates and month_dates:
                ev.applicable_dates = month_dates

        # Build data block for formatter LLM (NO price — advisor shows what to do, not cost)
        lines = []
        for ev in extraction.events:
            parts = [f"name: {ev.name}"]
            if ev.dates_display:  parts.append(f"dates: {ev.dates_display}")
            if ev.hours_display:  parts.append(f"hours: {ev.hours_display}")
            if ev.location:       parts.append(f"location: {ev.location}")
            parts.append(f"description: {ev.description}")
            lines.append("- " + " | ".join(parts))

        data_block = f"[{label}]\n" + "\n".join(lines)

        # Build state-compatible dicts for itinerary pipeline reuse
        events_for_state = [
            {
                "name":                 ev.name,
                "description":          ev.description,
                "applicable_dates":     ev.applicable_dates,
                "time_start":           ev.time_start,
                "time_end":             ev.time_end,
                "cost_usd":             ev.cost_usd,
                "suggested_visit_hours": ev.suggested_visit_hours,
                "is_evening_only":      ev.is_evening_only,
                "location_hint":        ev.location_hint or ev.location,
                "lat":                  None,
                "lng":                  None,
            }
            for ev in extraction.events
        ]

        return events_for_state, data_block

    # ------------------------------------------------------------------
    # Conversational synthesis (summary only, no tool names or user message)
    # ------------------------------------------------------------------

    def _render_conversational(self, state: AgentState, messages: list) -> str:
        summary = state.get("summary", "")
        last_human = next(
            (m for m in reversed(messages) if getattr(m, "type", "") == "human"), None
        )
        user_question = last_human.content if last_human else ""

        if not summary:
            return (
                "I don't have enough context from our conversation yet. "
                "Could you ask a more specific travel question and I'll do my best to help?"
            )

        response = self.model.invoke([
            {
                "role": "system",
                "content": _CONVERSATIONAL_SYSTEM.format(summary=summary),
            },
            {"role": "user", "content": user_question},
        ])
        return response.content

    # ------------------------------------------------------------------
    # City extraction for advisor_shown_cities state
    # ------------------------------------------------------------------

    def _extract_cities(self, response_text: str, state: AgentState) -> list[str]:
        try:
            extraction: _CityExtraction = self._city_extractor.invoke([
                {
                    "role": "system",
                    "content": (
                        "Extract every destination city name explicitly mentioned in this "
                        "travel advisor response. Return only real city names — "
                        "no countries, regions, or generic phrases."
                    ),
                },
                {"role": "user", "content": response_text},
            ])
            new_cities = set(extraction.cities)
        except Exception:
            new_cities = set()

        existing = set(state.get("advisor_shown_cities") or [])
        return sorted(existing | new_cities)
