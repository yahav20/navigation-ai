"""Formatter node — turns tool results into a natural advisor response via LLM.

Security model
--------------
The LLM formatter never sees:
  - The raw user message (style injection blocked — issues 5, 6, 7)
  - Tool names (tool-name leak blocked — issues 2, 3)
  - Full raw conversation history (scope drift blocked — issue 4)

What the LLM does see:
  - advisor_intent_summary: planner-generated one-sentence description of what was asked.
    Generated by the planner LLM, which has already passed the travel-relevance gate.
    Cannot contain style instructions — it's rephrased as a factual statement.
  - Structured data blocks: tool results formatted as clean key-value text without tool names.
    Data is validated (comes from our DB or schema-validated APIs).

Concerts: raw web snippets are first structured via Pydantic extraction, then the clean
structured data is passed to the main LLM formatter — same security properties.
"""
